package ru.aokazantsev.devatlas.themeformat.code.lexer

internal data class ProgramRules(
    val keywords: Set<String>,
    val types: Set<String> = emptySet(),
    val literals: Set<String> = setOf("true", "false", "null"),
    val lineComments: List<String> = listOf("//"),
    val blockComment: BlockComment? = BlockComment("/*", "*/"),
    val strings: List<StringRule> = listOf(StringRule("\""), StringRule("'")),
    val stringPrefixes: Set<String> = emptySet(),
    val annotationPrefix: Char? = null,
    val variablePrefixes: String = "",
    val identifierExtra: String = "",
    val markers: List<String> = emptyList(),
    val markupAfter: String? = null,
    val capitalizedTypes: Boolean = false,
    val ignoreCase: Boolean = false,
    val preprocessor: Boolean = false,
    val hashDirectives: Boolean = false,
    val hashAttributes: Boolean = false,
    val macros: Boolean = false,
    val lifetimes: Boolean = false,
    val rawHashStrings: Boolean = false,
    val regexLiterals: Boolean = false,
    val symbols: Boolean = false,
    val commentAfterSpaceOnly: Boolean = false,
    val escapesOutsideStrings: Boolean = false,
    val heredocs: HeredocStyle = HeredocStyle.NONE,
)
